    String query, {
    bool widgetSupported = true,
  }) {
    final q = _normalize(query.length > 120 ? query.substring(0, 120) : query);
    if (q.isEmpty) return [];
    final scored = <({FeatureSearchEntry entry, int score, int index})>[];
    for (var index = 0; index < entries.length; index++) {
      final entry = entries[index];
      if (!widgetSupported && entry.feature == AppFeature.homeWidget) continue;
      var score = 0;
      for (final phrase in [entry.ko, entry.en, ...entry.phrases]) {
        final term = _normalize(phrase);
        if (term == q) {
          score = score < 500 ? 500 : score;
        } else if (q.contains(term)) {
          final weight = 40 + term.length.clamp(0, 25) * 2;
          if (weight > score) score = weight;
        } else if (q.length >= 2 && term.contains(q)) {
          if (score < 20) score = 20;
        }
      }
      // 여러 단어의 순서·조사가 달라도 의도 그룹이 모두 있으면 함께 평가한다.
      if (entry.concepts.isNotEmpty &&
          entry.concepts.every(
            (group) => group.any((term) => q.contains(_normalize(term))),
          )) {
        score += entry.conceptBoost;
      }
      if (score > 0) scored.add((entry: entry, score: score, index: index));
    }
    scored.sort((a, b) {
      final order = b.score.compareTo(a.score);
      return order == 0 ? a.index.compareTo(b.index) : order;
    });
    return scored.map((item) => item.entry).toList(growable: false);
  }

  // 검색어 한 글자마다 모든 표현을 다시 정규화하므로 패턴은 한 번만 만든다.
  static final _ignored = RegExp(r'[^a-z0-9가-힣ㄱ-ㅎㅏ-ㅣ]');

  // 함수이름: _normalize
  // 함수역할: 비교할 때만 공백·문장부호를 제거하고 영문 대소문자를 통일한다.
  static String _normalize(String value) =>
      value.toLowerCase().replaceAll(_ignored, '');
}
