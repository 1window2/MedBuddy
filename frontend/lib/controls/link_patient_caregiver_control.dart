import 'dart:convert';
import 'dart:developer' as developer;

import 'package:http/http.dart' as http;

import '../entities/patient_caregiver_link_entity.dart';
import '../entities/patient_hash_entity.dart';
import '../services/api_config.dart';
import '../services/authenticated_api_client.dart';
import '../services/api_response_parser.dart';

// File Name: link_patient_caregiver_control.dart
// Role: Manages patient-caregiver link codes, registration, aliases, and unlink requests.

// 클래스명: LinkPatientCaregiver
// 역할: 환자 코드 생성, 보호자 등록, 연동 해제를 처리한다.
// 주요 책임:
// - 현재 사용자 해시 기준의 연동 목록을 조회한다.
// - 환자 측 임시 연동 코드를 생성한다.
// - 보호자 측에서 환자 코드를 등록하거나 기존 연동을 해제한다.
// 속성:
// - baseUrl (String): 복약 API 기본 주소
// - userHash (String): 현재 사용자 소유권·표시·저장 범위의 해시
// - _client (http.Client): 요청에 사용할 HTTP 클라이언트; 주입 여부에 따른 소유권은 생성자 설명 참조
class LinkPatientCaregiver {
  final String baseUrl;
  final String userHash;
  final http.Client _client;
  final bool _ownsClient;

  // Function Name: LinkPatientCaregiver
  // Description: Binds pairing, alias, and unlink requests to the current user hash and an injected or owned authenticated client.
  // Parameters:
  // - baseUrl (String): Base URL of the medication API.
  // - userHash (String): Current user hash defining ownership, display, or persistence scope.
  // - client (http.Client?): HTTP transport; constructor documentation specifies ownership for injected clients.
  // Returns:
  // - LinkPatientCaregiver: the initialized instance.
  LinkPatientCaregiver({
    this.baseUrl = ApiConfig.baseUrl,
    this.userHash = PatientHash.defaultPatientHash,
    http.Client? client,
  }) : _client = client ?? AuthenticatedApiClient(),
       _ownsClient = client == null;

  // Function Name: requestLinkScreen
  // Description: Reads active patient-caregiver links for the current user hash.
  // Parameters:
  // - None.
  // Returns:
  // - Active links for the current user hash.
  Future<List<PatientCaregiverLink>> requestLinkScreen() async {
    try {
      final response = await _client
          .get(_buildLinkUri('link/list'))
          .timeout(const Duration(seconds: 30));
      final responseBody = ApiResponseParser.decodeBody(response);

      if (response.statusCode != 200) {
        throw StateError(
          'Link lookup failed (${response.statusCode}): '
          '${ApiResponseParser.extractErrorDetail(responseBody)}',
        );
      }

      final decodedData = ApiResponseParser.decodeMap(responseBody);
      return _decodeLinkList(decodedData['data']);
    } on StateError {
      rethrow;
    } catch (error, stackTrace) {
      developer.log(
        'Patient-caregiver link lookup failed.',
        name: 'LinkPatientCaregiver',
        error: error,
        stackTrace: stackTrace,
      );
      throw StateError('Link lookup failed.');
    }
  }

  // Function Name: generatePatientHash
  // Description: Requests a temporary patient code for caregiver registration.
  // Parameters:
  // - None.
  // Returns:
  // - Generated patient code.
  Future<PatientLinkCode> generatePatientHash() async {
    try {
      final response = await _client
          .post(
            Uri.parse('$baseUrl/link/code'),
            headers: const {'Content-Type': 'application/json'},
            body: jsonEncode({'patient_hash': userHash}),
          )
          .timeout(const Duration(seconds: 30));
      final responseBody = ApiResponseParser.decodeBody(response);

      if (response.statusCode != 200) {
        throw StateError(
          'Patient code creation failed (${response.statusCode}): '
          '${ApiResponseParser.extractErrorDetail(responseBody)}',
        );
      }

      final decodedData = ApiResponseParser.decodeMap(responseBody);
      final rawData = decodedData['data'];
      if (rawData is Map) {
        return PatientLinkCode.fromJson(Map<String, dynamic>.from(rawData));
      }
      throw StateError('Server response did not include a patient code.');
    } on StateError {
      rethrow;
    } catch (error, stackTrace) {
      developer.log(
        'Patient code request failed.',
        name: 'LinkPatientCaregiver',
        error: error,
        stackTrace: stackTrace,
      );
      throw StateError('Patient code creation failed.');
    }
  }

  // Function Name: requestPatientCaregiverLink
  // Description: Registers the current caregiver hash with a patient code.
  // Parameters:
  // - patientCode (String): Temporary code generated by the patient.
  // Returns:
  // - Created patient-caregiver link.
  Future<PatientCaregiverLink> requestPatientCaregiverLink(
    String patientCode,
  ) async {
    try {
      final response = await _client
          .post(
            Uri.parse('$baseUrl/link/register'),
            headers: const {'Content-Type': 'application/json'},
            body: jsonEncode({
              'caregiver_hash': userHash,
              'patient_code': patientCode,
            }),
          )
          .timeout(const Duration(seconds: 30));
      final responseBody = ApiResponseParser.decodeBody(response);

      if (response.statusCode != 200) {
        throw StateError(
          'Patient registration failed (${response.statusCode}): '
          '${ApiResponseParser.extractErrorDetail(responseBody)}',
        );
      }

      return _decodeSingleLink(
        ApiResponseParser.decodeMap(responseBody)['data'],
      );
    } on StateError {
      rethrow;
    } catch (error, stackTrace) {
      developer.log(
        'Patient registration failed.',
        name: 'LinkPatientCaregiver',
        error: error,
        stackTrace: stackTrace,
      );
      throw StateError('Patient registration failed.');
    }
  }

  // 함수이름: savePatientAlias
  // 함수역할: 현재 보호자가 지정한 환자 표시 이름을 서버 연동 관계에 저장한다. 빈 문자열은 별칭을 삭제하고 기본 표시 이름으로 되돌린다.
  // 매개변수:
  // - linkId (int): 조회·전송·감시 대상 연동 ID
  // - patientAlias (String): 보호자가 설정한 환자 별칭; 빈 문자열은 별칭 해제
  // 반환값:
  // - Future<PatientCaregiverLink>: 현재 보호자가 지정한 환자 표시 이름을 서버 연동 관계에 저장한다. 빈 문자열은 별칭을 삭제하고 기본 표시 이름으로 되돌린다.
  Future<PatientCaregiverLink> savePatientAlias({
    required int linkId,
    required String patientAlias,
  }) async {
    try {
      final response = await _client
          .patch(
            _buildLinkUri('link/$linkId/patient-alias'),
            headers: const {'Content-Type': 'application/json'},
            body: jsonEncode({'patient_alias': patientAlias}),
          )
          .timeout(const Duration(seconds: 30));
      final responseBody = ApiResponseParser.decodeBody(response);
      if (response.statusCode != 200) {
        throw StateError(
          'Patient alias save failed (${response.statusCode}): '
          '${ApiResponseParser.extractErrorDetail(responseBody)}',
        );
      }
      return _decodeSingleLink(
        ApiResponseParser.decodeMap(responseBody)['data'],
      );
    } on StateError {
      rethrow;
    } catch (error, stackTrace) {
      developer.log(
        '환자 표시 이름 서버 저장에 실패했습니다.',
        name: 'LinkPatientCaregiver',
        error: error,
        stackTrace: stackTrace,
      );
      throw StateError('Patient alias save failed.');
    }
  }

  // Function Name: requestUnlink
  // Description: Removes one patient-caregiver link for the current user hash.
  // Parameters:
  // - linkId (int): Patient-caregiver link identifier.
  // Returns:
  // - Updated patient-caregiver link.
  Future<PatientCaregiverLink> requestUnlink(int linkId) async {
    try {
      final response = await _client
          .delete(_buildLinkUri('link/$linkId'))
          .timeout(const Duration(seconds: 30));
      final responseBody = ApiResponseParser.decodeBody(response);

      if (response.statusCode != 200) {
        throw StateError(
          'Unlink failed (${response.statusCode}): '
          '${ApiResponseParser.extractErrorDetail(responseBody)}',
        );
      }

      return _decodeSingleLink(
        ApiResponseParser.decodeMap(responseBody)['data'],
      );
    } on StateError {
      rethrow;
    } catch (error, stackTrace) {
      developer.log(
        'Patient-caregiver unlink failed.',
        name: 'LinkPatientCaregiver',
        error: error,
        stackTrace: stackTrace,
      );
      throw StateError('Unlink failed.');
    }
  }

  // Function Name: _decodeSingleLink
  // Description: Requires a link-shaped map and converts it to an entity, rejecting responses without a link payload.
  // Parameters:
  // - rawItem (dynamic): Raw server item or list before model conversion.
  // Returns:
  // - PatientCaregiverLink: Requires a link-shaped map and converts it to an entity, rejecting responses without a link payload.
  PatientCaregiverLink _decodeSingleLink(dynamic rawItem) {
    if (rawItem is Map) {
      return PatientCaregiverLink.fromJson(Map<String, dynamic>.from(rawItem));
    }
    throw StateError('Server response did not include a link.');
  }

  // Function Name: _decodeLinkList
  // Description: Converts map entries into patient-caregiver links and treats a nonlist payload as an empty link list.
  // Parameters:
  // - rawItems (dynamic): Raw server item or list before model conversion.
  // Returns:
  // - List<PatientCaregiverLink>: Converts map entries into patient-caregiver links and treats a nonlist payload as an empty link list.
  List<PatientCaregiverLink> _decodeLinkList(dynamic rawItems) {
    if (rawItems is! List) {
      return [];
    }

    return rawItems
        .whereType<Map>()
        .map(
          // Function Name: map callback
          // Description: Parses each patient-caregiver link returned by the server.
          // Parameters:
          // - item (Map): Current response or collection entry being transformed or checked.
          // Returns:
          // - The parsed link and its status metadata.
          (item) =>
              PatientCaregiverLink.fromJson(Map<String, dynamic>.from(item)),
        )
        .toList(growable: false);
  }

  // Function Name: _buildLinkUri
  // Description: Builds a link endpoint URI scoped to the current user hash.
  // Parameters:
  // - path (String): Relative path appended to the configured API resource.
  // Returns:
  // - Uri: Builds a link endpoint URI scoped to the current user hash.
  Uri _buildLinkUri(String path) {
    return Uri.parse(
      '$baseUrl/$path',
    ).replace(queryParameters: {'user_hash': userHash});
  }

  // Function Name: dispose
  // Description: Closes the HTTP client only when this control created it; injected clients remain owned by the caller.
  // Parameters:
  // - None.
  // Returns:
  // - No return value.
  void dispose() {
    if (_ownsClient) {
      _client.close();
    }
  }
}
